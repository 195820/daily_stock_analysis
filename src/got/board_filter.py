def is_noise_pattern(name: str) -> bool:
    """基于语义模式的噪声识别（精确集合之外的兜底，覆盖未来类似噪声）。"""
    # 统计指数族后缀：{主板|创业|科创|北证|全A|ETF} + {总值|流通|活筹|平均|均价|涨跌|停板|等权|中位}
    stat_prefixes = ("主板", "创业", "科创", "北证", "全A", "全Ａ", "ETF")
    stat_suffixes = ("总值", "流通", "活筹", "平均", "均价", "涨跌", "停板", "等权", "中位")
    for p in stat_prefixes:
        if name.startswith(p):
            for s in stat_suffixes:
                if name == p + s:
                    return True
    # 事件状态前缀（昨日X / 近期X / 最近X / 历史X / 即将X / 连续X / 预计X）
    event_prefixes = ("昨日", "近期", "最近", "历史", "即将", "连续", "预计")
    if any(name.startswith(p) for p in event_prefixes):
        return True
    # 通达信宏观分类壳（TDX + 行业名 或 TDX + 空格）
    if name.startswith("TDX"):
        return True
    return False


def is_noise_board(board_name: str) -> bool:
    """过滤非可交易噪声板块（统计指数/行情事件/财务标签/机构持仓/风格因子/公司动作）。

    保留：产业概念板块 + 地域板块（32 省）。

    三层判定：
      1. 精确集合 NOISE_BOARDS（已核对 222 条，零误杀）
      2. 语义模式 is_noise_pattern（统计指数族 + 事件状态前缀 + TDX 前缀）
      3. 不写白名单——动态发现保留，新产业概念自动进入
    """
    name = board_name.strip()
    if not name:
        return True
    if name in NOISE_BOARDS:
        return True
    return is_noise_pattern(name)
